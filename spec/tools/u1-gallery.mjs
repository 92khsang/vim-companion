// Throwaway U1 data/HTML preparation. Run from the repository root with Node 24.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { join } from "node:path";
import { vscodeThemes, vscodeCases, vscodeFixture } from "./u1-matrix.mjs";
const matrix = process.argv.includes("--matrix");

const root = fileURLToPath(new URL("../../", import.meta.url));
const u1 = join(root, "spikes/u1");
const gallery = join(u1, "gallery");
const read = (path) => JSON.parse(readFileSync(path, "utf8"));
const fixture = (file, id) => {
  const item = read(
    join(root, `spec/fixtures/hint-view/${file}.json`),
  ).cases.find((item) => item.id === id);
  if (!item) throw new Error(`Missing fixture: ${id}`);
  return item.rows;
};
mkdirSync(gallery, { recursive: true });
const longLabel = "Move editor to next pane";
if (longLabel.length !== 24)
  throw new Error("The long label must have 24 characters");
const data = {
  vim: read(join(u1, "vim-learning.json")),
  idle: { rows: fixture("menu", "root-vscode") },
  prefix: { rows: fixture("menu", "window-vscode") },
  badges: {
    rows: [
      ...fixture("badges", "each-kind-vscode").slice(0, 6),
      { key: "x", label: longLabel, group: false, badge: "unsupported" },
      ...fixture("badges", "each-kind-vscode").slice(6),
    ],
    visibleRows: 7,
  },
  grammar: {
    parts: [
      ["d", "Delete · operator"],
      ["w", "Next word · motion"],
    ],
  },
};
writeFileSync(join(gallery, "data.json"), JSON.stringify(data, null, 2) + "\n");
writeFileSync(
  join(u1, "vscode/web/data.js"),
  `// Generated by spec/tools/u1-gallery.mjs.\nconst U1_DATA = ${JSON.stringify(data, null, 2)};\n`,
);

if (process.argv.includes("--html") || matrix) {
  const theme = read(join(gallery, "vscode-theme.json"));
  const tokens = [
    "font-family",
    "font-size",
    "foreground",
    "descriptionForeground",
    "sideBar-background",
    "panel-background",
    "editor-background",
    "editor-font-family",
    "keybindingLabel-border",
    "keybindingLabel-bottomBorder",
    "keybindingLabel-background",
    "keybindingLabel-foreground",
    "badge-background",
    "badge-foreground",
    "widget-border",
    "textBlockQuote-background",
    "errorForeground",
    "editorWarning-foreground",
    "textLink-foreground",
  ];
  for (const token of tokens) {
    if (!theme.variables[`--vscode-${token}`])
      throw new Error(`Missing theme token: ${token}`);
  }
  writeFileSync(
    join(gallery, "theme.css"),
    `/* Captured from a sandbox VS Code webview; see vscode-theme.json. */\n:root {\n${tokens.map((token) => `  --vscode-${token}: ${theme.variables[`--vscode-${token}`]};`).join("\n")}\n}\n`,
  );
  const { page } = createRequire(import.meta.url)(join(u1, "vscode/page.cjs"));
  for (const name of ["styles.css", "renderer.js", "data.js"])
    copyFileSync(join(u1, "vscode/web", name), join(gallery, name));
  for (const state of [
    "idle",
    "prefix",
    "badges",
    "grammar",
    ...Object.keys(data.vim.scenarios),
  ]) {
    writeFileSync(
      join(gallery, `vscode-${state}.html`),
      page((name) => name, state, "'self'", "theme.css"),
    );
  }
  if (matrix) {
    for (const definition of vscodeThemes) {
      for (const host of ["sidebar", "panel"]) {
        const fixture = read(join(gallery, vscodeFixture(definition.id, host)));
        if (fixture.theme !== definition.name || fixture.host !== host)
          throw new Error(`Wrong fixture: ${definition.id} / ${host}`);
        for (const token of tokens)
          if (
            !fixture.variables[`--vscode-${token}`] &&
            token !== "textBlockQuote-background"
          )
            throw new Error(`Missing ${token} for ${definition.name}`);
        writeFileSync(
          join(gallery, `theme-${definition.id}-${host}.css`),
          `/* Captured sandbox ${host}: ${fixture.theme}. */\n:root {\n  --u1-color-scheme: ${definition.colorScheme};\n${tokens
            .filter((token) => fixture.variables[`--vscode-${token}`])
            .map(
              (token) =>
                `  --vscode-${token}: ${fixture.variables[`--vscode-${token}`]};`,
            )
            .join("\n")}\n}\n`,
        );
      }
    }
    for (const cell of vscodeCases) {
      writeFileSync(
        join(gallery, `${cell.name}.html`),
        page(
          (name) => name,
          cell.state,
          "'self'",
          `theme-${cell.theme}-${cell.host}.css`,
          cell.host,
        ),
      );
    }
  }
}
console.log(
  "U1 data prepared" +
    (process.argv.includes("--html") ? " with ten webview pages" : ""),
);
